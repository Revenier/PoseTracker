from flask import Flask, request, jsonify
from flask_cors import CORS
import numpy as np

from app.logic import landmark_logic, angle_logic
from app import data_loader as dl
from app.data_loader import posture_map

app = Flask(__name__)
CORS(app)

@app.route('/pose', methods=['POST'])
def receive_pose():
    data = request.get_json()
    print(f"Received data: {data}")
    posture = data.get('posture')
    mediapipe = data.get('mediapipe', [])

    if posture not in posture_map:
        return jsonify({'status': 'error', 'message': 'Unknown posture'}), 400

    feedback_list = []
    for sample in mediapipe:
        if len(sample) != 99:
            feedback_list.append({
                'landmarks': f'Input data must have 99 values (got {len(sample)})',
                'angles': f'Input data must have 99 values (got {len(sample)})'
            })
            continue
        input_np = np.array(sample)
        feedback_list.append({
            'landmarks': landmark_logic(posture, input_np),
            'angles': angle_logic(posture, input_np)
        })

    # Check if all are good
    all_good = all(
        (fb['landmarks'] == "Correct form!" or fb['landmarks'] == "Correct posture!") and
        (fb['angles'] == "Correct posture!" or fb['angles'] == "Correct form!")
        for fb in feedback_list
    )

    if all_good:
        feedback = "Good pose!"
    else:
        # Join all feedbacks in a line if any is bad
        feedback = " | ".join(
            f"Sample {i+1}: landmarks: {fb['landmarks']}, angles: {fb['angles']}"
            for i, fb in enumerate(feedback_list)
        )

    print({'feedback': feedback})

    return jsonify({
        'status': 'success',
        'feedback': feedback
    }), 200

